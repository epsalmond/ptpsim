    fn raf_thumbnail_uses_exif_thumbnail_not_header_preview() {
        let root = tmpdir();
        let thumbnail = b"\xff\xd8TINY-THUMB\xff\xd9";
        let full_marker = b"FULL-HEADER-PREVIEW";
        let preview = jpeg_with_exif_thumbnail(thumbnail, full_marker);
        let raf = raf_with_header_preview(&preview);
        write(&root.join("DCIM/100_FUJI/DSCF9.RAF"), &raf);

        let mut store = MediaStore::open(&root).unwrap();
        store.scan().unwrap();
        let h = store.handles(ObjectQuery {
            parent: None,
            format: Some(fmt::RAF),
        })[0];
        let preview_span = raf_header_preview(&root.join("DCIM/100_FUJI/DSCF9.RAF"))
            .unwrap()
            .expect("RAF header preview");
        assert_eq!(preview_span.offset, 0x94);
        assert_eq!(preview_span.len, preview.len() as u64);

        let src = store.thumbnail(h).unwrap();
        if let ByteSource::FileRange { offset, len, .. } = &src {
            assert_ne!(*offset, preview_span.offset);
            assert_eq!(*len, thumbnail.len() as u64);
        } else {
            panic!("expected a bounded FileRange");
        }
        let bytes = src.read().unwrap();
        assert_eq!(bytes, thumbnail);
        std::fs::remove_dir_all(&root).ok();
    }

    #[test]
    fn oversize_mov_is_ceilinged_without_allocation() {
        let root = tmpdir();
        let p = root.join("DCIM/100_FUJI/BIG.MOV");
        std::fs::create_dir_all(p.parent().unwrap()).unwrap();
        // 5 GiB sparse file: set_len does not allocate blocks.
        let f = File::create(&p).unwrap();
        let five_gib = 5u64 * 1024 * 1024 * 1024;
        f.set_len(five_gib).unwrap();
        drop(f);

        let mut store = MediaStore::open(&root).unwrap();
        store.scan().unwrap();
        let h = store.handles(ObjectQuery {
            parent: None,
            format: Some(fmt::MOV),
        })[0];

        // Real size known; ObjectInfo reports the 32-bit ceiling.
        assert_eq!(store.object_size(h).unwrap(), five_gib);
        assert_eq!(
            store.object_info(h).unwrap().object_compressed_size,
            0xffff_ffff
        );
        assert!(store.is_memory_card_only(h).unwrap());

        // A partial read near the end works, allocating only the window.
        let src = store.read_range(h, five_gib - 8, 16).unwrap();
        assert_eq!(src.len(), 8); // clamped to remaining
        assert_eq!(src.read().unwrap().len(), 8);
        std::fs::remove_dir_all(&root).ok();
    }

    #[test]
    fn read_chunk_streams_without_realizing_full_window() {
        let root = tmpdir();
        let p = root.join("DCIM/100_FUJI/BIG.MOV");
        std::fs::create_dir_all(p.parent().unwrap()).unwrap();
        // 5 GiB sparse file. The whole-window allocation would OOM the test;
        // streaming should bound the allocation by chunk size.
        let f = File::create(&p).unwrap();
        let five_gib = 5u64 * 1024 * 1024 * 1024;
        f.set_len(five_gib).unwrap();
        drop(f);

        // FileRange spanning the full file, larger than any sane buffer.
        let src = ByteSource::FileRange {
            path: p.clone(),
            offset: 0,
            len: five_gib,
        };
        // One chunk reads at most `max` bytes regardless of total length.
        let chunk = src.read_chunk(0, 256 * 1024).unwrap();
        assert_eq!(chunk.len(), 256 * 1024);
        // The last chunk is short.
        let tail = src.read_chunk(five_gib - 100, 256 * 1024).unwrap();
        assert_eq!(tail.len(), 100);
        // Past-the-end is empty, not an error.
        assert!(src.read_chunk(five_gib, 256 * 1024).unwrap().is_empty());
        std::fs::remove_dir_all(&root).ok();
    }

    #[test]
    fn read_chunk_memory_and_generated() {
        let mem = ByteSource::Memory(vec![1, 2, 3, 4, 5, 6, 7, 8]);
        assert_eq!(mem.read_chunk(0, 3).unwrap(), vec![1, 2, 3]);
        assert_eq!(mem.read_chunk(5, 100).unwrap(), vec![6, 7, 8]);
        assert!(mem.read_chunk(8, 1).unwrap().is_empty());

        let gen = ByteSource::Generated {
            len: 1_000_000,
            seed: 42,
        };
        let first = gen.read_chunk(0, 16).unwrap();
        let again = gen.read_chunk(0, 16).unwrap();
        assert_eq!(first, again, "seeded generator is deterministic");
        assert_eq!(first.len(), 16);
    }
