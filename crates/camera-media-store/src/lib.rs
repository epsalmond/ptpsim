        tiff.extend_from_slice(&1u32.to_le_bytes());
        tiff.extend_from_slice(&thumbnail_offset.to_le_bytes());
        tiff.extend_from_slice(&0x0202u16.to_le_bytes());
        tiff.extend_from_slice(&4u16.to_le_bytes());
