//! Snapshot the public UniFFI surface of a library and compare it with a
//! committed baseline. `ci/ffi-surface.sh` builds the inputs and runs this.
//!
//! Exit status: 0 when nothing breaks (additions are reported), 1 when an
//! item was removed or changed, 2 on a usage or input error.

mod compare;
mod render;

use std::fmt::Write as _;
use std::path::PathBuf;
use std::process::ExitCode;

use compare::{Finding, Severity};

const UPDATE_COMMAND: &str = "ci/ffi-surface.sh update";

const PREAMBLE: &str = "\
# Public UniFFI surface of camera-protocol-ffi: the items the generated Swift
# and Kotlin bindings expose. Generated by `ci/ffi-surface.sh update`; do not
# edit by hand. CI fails when an item here is removed or changed. See
# docs/APPLE_FFI_RELEASES.md, \"FFI surface baseline\".
";

const USAGE: &str = "\
usage: ffi-surface snapshot --library <lib> --config <uniffi.toml> --lockfile <Cargo.lock> --output <file>
       ffi-surface check    --library <lib> --config <uniffi.toml> --lockfile <Cargo.lock> --baseline <file>";

struct Args {
    command: String,
    library: PathBuf,
    config: PathBuf,
    lockfile: PathBuf,
    file: PathBuf,
}

fn parse_args() -> Result<Args, String> {
    let mut args = std::env::args().skip(1);
    let command = args.next().ok_or(USAGE)?;
    let file_flag = match command.as_str() {
        "snapshot" => "--output",
        "check" => "--baseline",
        _ => return Err(USAGE.into()),
    };
    let (mut library, mut config, mut lockfile, mut file) = (None, None, None, None);
    while let Some(flag) = args.next() {
        let value = args.next().map(PathBuf::from).ok_or(USAGE)?;
        match flag.as_str() {
            "--library" => library = Some(value),
            "--config" => config = Some(value),
            "--lockfile" => lockfile = Some(value),
            f if f == file_flag => file = Some(value),
            _ => return Err(USAGE.into()),
        }
    }
    Ok(Args {
        command,
        library: library.ok_or(USAGE)?,
        config: config.ok_or(USAGE)?,
        lockfile: lockfile.ok_or(USAGE)?,
        file: file.ok_or(USAGE)?,
    })
}

fn read(path: &PathBuf) -> Result<String, String> {
    std::fs::read_to_string(path).map_err(|e| format!("{}: {e}", path.display()))
}

fn current_surface(args: &Args) -> Result<Vec<compare::Item>, String> {
    let library =
        std::fs::read(&args.library).map_err(|e| format!("{}: {e}", args.library.display()))?;
    let metadata = uniffi_bindgen::macro_metadata::extract_from_bytes(&library)
        .map_err(|e| format!("{}: {e:#}", args.library.display()))?;
    if metadata.is_empty() {
        return Err(format!(
            "{}: no UniFFI metadata found",
            args.library.display()
        ));
    }
    let config: toml::Table = toml::from_str(&read(&args.config)?)
        .map_err(|e| format!("{}: {e}", args.config.display()))?;
    let version = render::generator_version(&read(&args.lockfile)?)?;
    render::items(metadata, &render::config_entries(&config), &version)
}

fn report(baseline: &str, findings: &[Finding]) -> String {
    let mut out = String::new();
    let section = |out: &mut String, title: &str, severity: Severity| {
        let selected: Vec<&Finding> = findings.iter().filter(|f| f.severity == severity).collect();
        if selected.is_empty() {
            return;
        }
        let _ = writeln!(out, "\n{title} ({}):", selected.len());
        for finding in selected {
            let _ = writeln!(out, "  {}", finding.summary);
            for line in &finding.detail {
                let _ = writeln!(out, "      {line}");
            }
        }
    };
    let _ = writeln!(out, "FFI surface compared with {baseline}");
    section(&mut out, "Breaking changes", Severity::Breaking);
    section(&mut out, "Additions", Severity::Addition);
    let breaking = findings.iter().any(|f| f.severity == Severity::Breaking);
    let additions = findings.iter().any(|f| f.severity == Severity::Addition);
    if breaking {
        let _ = writeln!(
            out,
            "\nThe breaking changes above remove or change items that the generated Swift\n\
             and Kotlin bindings expose. Code that vendors the bindings and uses those\n\
             items stops compiling. If the break is intended, update the baseline in\n\
             this pull request so it is visible in review:\n\n    \
             {UPDATE_COMMAND}\n    git add {baseline}\n\n\
             Otherwise restore the items."
        );
    } else if additions {
        let _ = writeln!(
            out,
            "\nNo breaking changes. The baseline is missing the additions above. Update it\n\
             in this pull request so a later removal of these items is detected:\n\n    \
             {UPDATE_COMMAND}\n    git add {baseline}"
        );
    } else {
        let _ = writeln!(out, "\nNo differences.");
    }
    out
}

/// GitHub Actions workflow commands: one annotation per finding and a job
/// summary. Annotation text escapes `%`, CR and LF as the runner requires.
fn github_annotations(findings: &[Finding], text: &str) {
    if std::env::var("GITHUB_ACTIONS").as_deref() != Ok("true") {
        return;
    }
    let escape = |s: &str| {
        s.replace('%', "%25")
            .replace('\r', "%0D")
            .replace('\n', "%0A")
    };
    for finding in findings {
        let message = std::iter::once(finding.summary.clone())
            .chain(finding.detail.iter().cloned())
            .collect::<Vec<_>>()
            .join("\n");
        let (level, title) = match finding.severity {
            Severity::Breaking => ("error", "FFI surface break"),
            Severity::Addition => ("warning", "FFI surface addition missing from baseline"),
        };
        println!("::{level} title={title}::{}", escape(&message));
    }
    if let Ok(path) = std::env::var("GITHUB_STEP_SUMMARY") {
        let summary = format!("## FFI surface\n\n```text\n{text}```\n");
        let appended = std::fs::OpenOptions::new()
            .append(true)
            .create(true)
            .open(path)
            .and_then(|mut file| std::io::Write::write_all(&mut file, summary.as_bytes()));
        if let Err(error) = appended {
            eprintln!("warning: could not write the job summary: {error}");
        }
    }
}

fn run() -> Result<ExitCode, String> {
    let args = parse_args()?;
    let current = current_surface(&args)?;
    if args.command == "snapshot" {
        std::fs::write(&args.file, render::text(PREAMBLE, &current))
            .map_err(|e| format!("{}: {e}", args.file.display()))?;
        println!("wrote {} ({} items)", args.file.display(), current.len());
        return Ok(ExitCode::SUCCESS);
    }
    let baseline_text = read(&args.file)?;
    let baseline =
        compare::parse(&baseline_text).map_err(|e| format!("{}: {e}", args.file.display()))?;
    let findings = compare::compare(&baseline, &current);
    let text = report(&args.file.display().to_string(), &findings);
    print!("{text}");
    github_annotations(&findings, &text);
    let breaking = findings.iter().any(|f| f.severity == Severity::Breaking);
    Ok(if breaking {
        ExitCode::from(1)
    } else {
        ExitCode::SUCCESS
    })
}

fn main() -> ExitCode {
    match run() {
        Ok(code) => code,
        Err(message) => {
            eprintln!("ffi-surface: {message}");
            ExitCode::from(2)
        }
    }
}
